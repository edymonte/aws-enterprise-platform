<#
.SYNOPSIS
  Terraform outputs (40-eks, 60-observability) -> GitOps values files.

.DESCRIPTION
  The "contract" between infrastructure (Terraform) and delivery (GitOps).
  Writes gitops/envs/<env>/platform.values.yaml and the Grafana AMP data source.
  Commit the result through a PR — Git stays the source of truth.
#>
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$Root = Split-Path $PSScriptRoot -Parent
$awp = Join-Path $PSScriptRoot 'awp.ps1'

function Get-Outputs([string]$Layer) {
  & $awp init $Layer | Out-Null
  (& terraform "-chdir=$(Join-Path $Root "infra/terraform/$Layer")" output -json) | ConvertFrom-Json
}

$eks = Get-Outputs '40-eks'
if (-not $eks.ecr_registry) { throw '40-eks has no outputs. Apply it first.' }

foreach ($env in 'dev', 'prod') {
  $file = Join-Path $Root "gitops/envs/$env/platform.values.yaml"
  @"
# GENERATED by scripts/render-gitops-values.ps1 from Terraform outputs
# (40-eks). Names are stable across the daily rebuild (name_suffix), but the
# security group ID changes: re-render after recreating 40-eks.
image:
  registry: $($eks.ecr_registry.value)
ingress:
  securityGroupId: $($eks.alb_security_group_id.value)
database:
  host: $($eks.db_address.value)
secrets:
  bannerSecretName: $($eks.banner_secret_name.value)
networkPolicy:
  allowedCidrs:
    - $($eks.vpc_cidr.value)
"@ | Set-Content $file -Encoding utf8
  Write-Host "wrote $file"
}

try {
  $obs = Get-Outputs '60-observability'
  if ($obs.amp_query_endpoint) {
    $file = Join-Path $Root 'gitops/platform/grafana/amp-datasource.values.yaml'
    @"
# GENERATED by scripts/render-gitops-values.ps1 from Terraform outputs (60-observability).
datasources:
  datasources.yaml:
    apiVersion: 1
    datasources:
      - name: Amazon Managed Prometheus
        type: prometheus
        uid: amp
        access: proxy
        isDefault: true
        url: $($obs.amp_query_endpoint.value)
        jsonData:
          sigV4Auth: true
          sigV4AuthType: default
          sigV4Region: $($eks.region.value)
"@ | Set-Content $file -Encoding utf8
    Write-Host "wrote $file"
  }
} catch { Write-Host '60-observability not applied yet — Grafana data source skipped.' }

Write-Host "`nNext: open a PR with the changes under gitops/."
